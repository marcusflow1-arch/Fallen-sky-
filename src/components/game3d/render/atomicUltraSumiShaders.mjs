export const ATOMIC_WORLD_FRAGMENT=[
'precision highp float;',
'uniform float uTime,uMode,uEnergyIntensity,uWindStrength,uFamily;',
'varying vec3 vWorld,vNormal;',
'varying vec2 vUv;',
'float hash3(vec3 p){p=fract(p*.1031);p+=dot(p,p.yxz+33.33);return fract((p.x+p.y)*p.z);}',
'float noise3(vec3 p){vec3 i=floor(p),f=fract(p);f=f*f*(3.-2.*f);',
' float a=mix(hash3(i),hash3(i+vec3(1,0,0)),f.x);',
' float b=mix(hash3(i+vec3(0,1,0)),hash3(i+vec3(1,1,0)),f.x);',
' float c=mix(hash3(i+vec3(0,0,1)),hash3(i+vec3(1,0,1)),f.x);',
' float d=mix(hash3(i+vec3(0,1,1)),hash3(i+vec3(1,1,1)),f.x);',
' return mix(mix(a,b,f.y),mix(c,d,f.y),f.z);}',
'float voronoi3(vec3 p){vec3 i=floor(p),f=fract(p);float nearest=4.;',
' for(int z=-1;z<=1;z++)for(int y=-1;y<=1;y++)for(int x=-1;x<=1;x++){',
' vec3 q=vec3(float(x),float(y),float(z));',
' vec3 h=vec3(hash3(i+q),hash3(i+q+17.),hash3(i+q+37.));',
' nearest=min(nearest,length(q+h*.85-f));',
' }return nearest;}',
'void main(){',
' vec3 n=normalize(vNormal),eye=normalize(cameraPosition-vWorld);',
' float rim=pow(1.0-clamp(dot(eye,n),0.0,1.0),3.5);',
' float light=clamp(dot(n,normalize(vec3(.4,.8,.45)))*.55+.48,0.,1.);',
' float cel=floor(light*4.)/3.;',
' vec3 core=mix(vec3(.06,.18,.19),vec3(.70,.86,.74),cel);',
' if(uFamily>0.5&&uFamily<1.5)core=mix(vec3(.02,.21,.14),vec3(.20,.78,.59),cel);',
' if(uFamily>1.5&&uFamily<2.5)core=mix(vec3(.05,.20,.16),vec3(.49,.82,.59),cel);',
' if(uFamily>2.5&&uFamily<3.5)core=mix(vec3(.09,.12,.2),vec3(.58,.67,.79),cel);',
' if(uFamily>3.5&&uFamily<4.5)core=mix(vec3(.12,.13,.20),vec3(.77,.66,.50),cel);',
' if(uFamily>4.5&&uFamily<5.5)core=mix(vec3(.17,.13,.22),vec3(.85,.75,.68),cel);',
' if(uFamily>5.5&&uFamily<6.5)core=mix(vec3(.025,.15,.32),vec3(.08,.65,.83),cel);',
' vec3 p=vWorld*.41+vec3(0.,-uTime*.64,0.);',
' // Finite-difference curl field; two Voronoi octaves for atomic plasma.',
' float e=.1;',
' vec2 curl=vec2(noise3(p+vec3(0,e,0))-noise3(p-vec3(0,e,0)),',
'                noise3(p+vec3(e,0,0))-noise3(p-vec3(e,0,0)))/(2.*e);',
' p.xy+=curl*.22;',
' float cells=voronoi3(p*1.25)*.67+voronoi3(p*2.5)*.33;',
' float streak=sin(vUv.y*25.0-uTime*4.0+noise3(p*3.)*12.);',
' float plasma=smoothstep(.43,.88,1.-cells+.11*streak)*(.29+.71*rim);',
' float dry=noise3(vWorld*vec3(1.1,6.2,1.1)+vec3(0.,uTime*.12,0.));',
' core=mix(core,vec3(.006,.010,.02),smoothstep(.63,.83,dry)*plasma*.86);',
' vec3 cobalt=vec3(.102,.4,1.),cyan=vec3(0.,.898,1.),violet=vec3(.357,.18,1.);',
' vec3 aura=mix(cobalt,cyan,smoothstep(.3,.83,plasma));',
' aura=mix(aura,violet,smoothstep(.60,.9,dry)*.56);',
' core=mix(core,aura,plasma*.76*uEnergyIntensity);',
' core=mix(core,vec3(.94,.96,1.0)+aura*.32,smoothstep(.51,.91,rim)*uEnergyIntensity);',
' if(uFamily>.5&&uFamily<1.5){',
'   float vein=1.-smoothstep(.02,.13,abs(vUv.x-.5));',
'   core=mix(core,vec3(.9,.99,1.),vein*.52);',
'   float tip=smoothstep(.65,1.,vUv.y);',
'   if(tip*noise3(vWorld*vec3(3.,7.,3.)-vec3(0.,uTime*.8,0.))*uWindStrength>.7)discard;',
'   core+=tip*plasma*vec3(.18,.32,.60)*uEnergyIntensity;',
' }',
' gl_FragColor=vec4(clamp(core,0.,2.),1.);',
'}'].join('\n');

