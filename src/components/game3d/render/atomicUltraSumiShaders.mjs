export const ATOMIC_SOBEL_FRAGMENT=[
'uniform sampler2D tDiffuse;',
'uniform vec2 uResolution;',
'varying vec2 vUv;',
'void main(){',
' vec2 d=1./uResolution;',
' vec3 c=texture2D(tDiffuse,vUv).rgb;',
' vec3 lum=vec3(.2126,.7152,.0722);',
' float tl=dot(texture2D(tDiffuse,vUv+vec2(-d.x,d.y)).rgb,lum);',
' float t=dot(texture2D(tDiffuse,vUv+vec2(0.,d.y)).rgb,lum);',
' float tr=dot(texture2D(tDiffuse,vUv+vec2(d.x,d.y)).rgb,lum);',
' float l=dot(texture2D(tDiffuse,vUv-vec2(d.x,0.)).rgb,lum);',
' float r=dot(texture2D(tDiffuse,vUv+vec2(d.x,0.)).rgb,lum);',
' float bl=dot(texture2D(tDiffuse,vUv-vec2(d.x,d.y)).rgb,lum);',
' float b=dot(texture2D(tDiffuse,vUv-vec2(0.,d.y)).rgb,lum);',
' float br=dot(texture2D(tDiffuse,vUv+vec2(d.x,-d.y)).rgb,lum);',
' float dx=-tl-2.*l-bl+tr+2.*r+br;',
' float dy=-bl-2.*b-br+tl+2.*t+tr;',
' float edge=smoothstep(.16,.67,length(vec2(dx,dy)));',
' float grain=fract(sin(dot(floor(gl_FragCoord.xy*.72),vec2(12.9898,78.233)))*43758.5453);',
' vec3 ink=mix(vec3(.009,.010,.022),vec3(.12,.31,.60),smoothstep(.35,.8,grain)*.32);',
' c=mix(c,ink,edge*.71);',
' float high=smoothstep(.73,1.2,dot(c,vec3(.21,.72,.07)));',
' c=mix(c,vec3(.93,.97,1.),edge*high*.63);',
' gl_FragColor=vec4(c,1.);',
'}'].join('\n');

